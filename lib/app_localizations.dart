                const Spacer(),
                Icon(Icons.check_rounded, color: Theme.of(context).primaryColor, size: 18),
              ],
            ],
          ),
        );
      }).toList(),
    );
  }
}

class TranslatedText extends StatefulWidget {
  final String text;
  final TextStyle? style;
  final TextAlign? textAlign;
  final TextDirection? textDirection;
  final int? maxLines;
  final TextOverflow? overflow;

  const TranslatedText(
    this.text, {
    super.key,
    this.style,
    this.textAlign,
    this.textDirection,
    this.maxLines,
    this.overflow,
  });

  @override
  State<TranslatedText> createState() => _TranslatedTextState();
}

class _TranslatedTextState extends State<TranslatedText> {
  String? _translatedText;
  Locale? _lastLocale;

  @override
  Widget build(BuildContext context) {
    final locale = Localizations.localeOf(context);
    final appLoc = AppLocalizations.of(context);
    final localTranslation = appLoc.translate(widget.text);

    if (localTranslation != widget.text) {
      return Text(
        localTranslation,
        style: widget.style,
        textAlign: widget.textAlign,
        textDirection: widget.textDirection,
        maxLines: widget.maxLines,
        overflow: widget.overflow,
      );
    }

    final bool isTest =
    !kIsWeb && std_io.Platform.environment.containsKey('FLUTTER_TEST');
    if (isTest) {
      return Text(
        widget.text,
        style: widget.style,
        textAlign: widget.textAlign,
        textDirection: widget.textDirection,
        maxLines: widget.maxLines,
        overflow: widget.overflow,
      );
    }

    if (_lastLocale != locale) {
      _lastLocale = locale;
      _translatedText = null;
      _fetchTranslation(widget.text, locale.languageCode);
    }

    return Text(
      _translatedText ?? widget.text,
      style: widget.style,
      textAlign: widget.textAlign,
      textDirection: widget.textDirection,
      maxLines: widget.maxLines,
      overflow: widget.overflow,
    );
  }

  Future<void> _fetchTranslation(String text, String targetLang) async {
    // If language is Urdu, keep it as is (default fallback is Urdu in the system)
    if (targetLang == 'ur' || text.trim().isEmpty || RegExp(r'^\d+$').hasMatch(text)) {
      if (mounted) {
        setState(() {
          _translatedText = text;
        });
      }
      return;
    }

    final translated = await GoogleTranslateService.translate(text, targetLang);
    if (mounted) {
      setState(() {
        _translatedText = translated;
      });
    }
  }
}
